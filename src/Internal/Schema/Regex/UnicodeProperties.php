    /** Returns the PCRE name of a property, or null if ECMA-262 doesn't know it. */
    public static function resolve(string $name): string|null
    {
        $valid = preg_match('/^[A-Za-z0-9_]+(=[A-Za-z0-9_]+)?$/', $name) === 1;
        if (!$valid) {
            return null;
        }
        $equals = strpos($name, needle: '=');
        if ($equals === false) {
            return self::LONE_NAMES[$name] ?? null;
        }
        $value = substr($name, $equals + 1);
        $property = substr($name, offset: 0, length: $equals);
        if ($property === 'General_Category' || $property === 'gc') {
            return self::GENERAL_CATEGORIES[$value] ?? null;
        }
        if (!in_array($value, self::SCRIPTS, strict: true)) {
            return null;
        }
        return match ($property) {
            'Script', 'sc' => 'sc:' . $value,
            'Script_Extensions', 'scx' => 'scx:' . $value,
            default => null,
        };
    }
